// Writes THIRD-PARTY-NOTICES.md: every production dependency (name, version, license, license text) plus what
// electron-builder ships (Electron and Chromium). Usage: node scripts/third-party-notices.mjs
// Licenses outside the allow-list are reported as findings at the top of the file; this script does not decide on them.
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');

const COMPATIBLE = ['MIT', 'BSD', 'ISC', 'Apache-2.0', 'AGPL', 'LGPL', 'MPL', '0BSD', 'CC0', 'Unlicense', 'BlueOak'];
const isCompatible = (expr) =>
  expr
    .split(/[\s()]+|\bOR\b|\bAND\b/)
    .filter((t) => t && t !== 'OR' && t !== 'AND' && t !== 'WITH')
    .every((t) => COMPATIBLE.some((c) => t.toUpperCase().startsWith(c.toUpperCase())));

const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: root, maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }).toString());

/** Walk the tree; map "name@version" to the node_modules directory it resolves to. */
const found = new Map();
function walk(deps, parentDir) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (!info.version) continue;
    // Resolve like Node: nearest node_modules up from the parent.
    let dir = null;
    for (let base = parentDir; base.startsWith(root); base = dirname(base)) {
      const cand = join(base, 'node_modules', name);
      if (existsSync(join(cand, 'package.json'))) { dir = cand; break; }
    }
    dir ??= existsSync(join(nm, name, 'package.json')) ? join(nm, name) : null;
    const key = `${name}@${info.version}`;
    if (!found.has(key)) found.set(key, dir);
    walk(info.dependencies, dir ?? parentDir);
  }
}
walk(tree.dependencies, root);

function licenseOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (!l) return 'UNKNOWN';
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(' OR ');
  return l.type ?? 'UNKNOWN';
}
function licenseText(dir) {
  const files = readdirSync(dir).filter((f) => /^(licen[sc]e|copying|notice)/i.test(f));
  return files.map((f) => `--- ${f} ---\n${readFileSync(join(dir, f), 'utf8').trim()}`).join('\n\n');
}

const rows = [];
for (const [key, dir] of [...found].sort(([a], [b]) => a.localeCompare(b))) {
  const [name, version] = [key.slice(0, key.lastIndexOf('@')), key.slice(key.lastIndexOf('@') + 1)];
  if (!dir) { rows.push({ name, version, license: 'UNKNOWN (not installed)', text: '' }); continue; }
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  rows.push({ name, version, license: licenseOf(pkg), text: licenseText(dir) });
}

const findings = rows.filter((r) => r.license === 'UNKNOWN' || !isCompatible(r.license));
const electronVersion = JSON.parse(readFileSync(join(nm, 'electron', 'package.json'), 'utf8')).version;
const chromiumFile = join(nm, 'electron', 'dist', 'LICENSES.chromium.html');
const electronLicense = existsSync(join(nm, 'electron', 'dist', 'LICENSE')) ? readFileSync(join(nm, 'electron', 'dist', 'LICENSE'), 'utf8').trim() : 'See https://github.com/electron/electron/blob/main/LICENSE (MIT).';

let out = `# Third-party notices

PDF Suite is licensed under AGPL-3.0-or-later (see LICENSE). It includes the components below.
Generated by scripts/third-party-notices.mjs. Do not edit by hand.

## License findings (not AGPL-compatible by the project's allow-list, or unknown)

`;
out += findings.length ? findings.map((r) => `- ${r.name}@${r.version}: ${r.license}`).join('\n') : 'None.';
out += `

Allow-list: ${COMPATIBLE.join(', ')}. Anything else is listed above for the owner to decide.

## Runtime shipped by electron-builder

- Electron ${electronVersion}: MIT license.
- Chromium and its bundled components: see the full list of licenses in LICENSES.chromium.html, which is shipped next to the app executable (source: node_modules/electron/dist/LICENSES.chromium.html${existsSync(chromiumFile) ? '' : '; NOT FOUND in this install'}).

\`\`\`
${electronLicense}
\`\`\`

## Production dependencies (${rows.length})

| Package | Version | License |
| --- | --- | --- |
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')}

`;
for (const r of rows) {
  out += `## ${r.name} ${r.version}\n\nLicense: ${r.license}\n\n${r.text ? '```\n' + r.text + '\n```' : '(No license file in the package.)'}\n\n`;
}
writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), out);
console.log(`${rows.length} packages, ${findings.length} finding(s)`);
for (const f of findings) console.log(`FINDING ${f.name}@${f.version}: ${f.license}`);
