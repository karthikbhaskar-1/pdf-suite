// Lists the files that would be published, with sizes, and fails on: files over 5 MB, personal-data patterns,
// PDFs not made by tests/fixtures/make-fixtures.mjs.
// Usage: node scripts/publish-check.mjs [folder] [--write-list]
//   no folder: scans `git ls-files` of the current tree and rewrites docs/release/FILE-LIST.md.
//   folder:    scans every file in that folder (dotfiles included; .git skipped). The list is written to this
//              repository's docs/release/FILE-LIST.md only with --write-list (used on an export folder).
// A line can opt out with the text "publish-check-ignore" on the same line (use sparingly, for patterns used as detectors).
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const folderArg = args.find((a) => !a.startsWith('--'));
const root = folderArg ? resolve(folderArg) : repoRoot;
const writeList = !folderArg || args.includes('--write-list');
const MAX = 5 * 1024 * 1024;
// This file lists the generic patterns, so only the local (personal) patterns are applied to it.
const SELF = 'scripts/publish-check.mjs';

// Personal patterns (names, machine and app names, the repository-URL exception) live in a git-ignored local file,
// so they are never published with this script.
const LOCAL_FILE = join(repoRoot, '.publish-patterns.local.json');
let LOCAL = [];
let EXCEPTIONS = [];
if (existsSync(LOCAL_FILE)) {
  const j = JSON.parse(readFileSync(LOCAL_FILE, 'utf8'));
  LOCAL = (j.patterns ?? []).map(([name, src, flags]) => [name, new RegExp(src, flags ?? '')]);
  EXCEPTIONS = (j.exceptions ?? []).map((e) => ({ pattern: e.pattern, re: new RegExp(e.lineRegex) }));
} else {
  console.log('NOTE: .publish-patterns.local.json is missing; only the generic patterns are checked.');
}

const GENERIC = [
  ['email address', /[\w.+-]+@[\w-]+\.[a-z]{2,}/i],
  ['Windows user path', /[A-Za-z]:[\\\/]+Users[\\\/]+/i],
  ['/Users/<name> path', /\/Users\/[A-Za-z0-9._-]+/],
  ['Tailscale-style IP', /(?<![\d.])100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d{1,3}\.\d{1,3}(?![\d])/],
  ['192.168.', /192\.168\./],
  ['private IPv4 10.x', /(?<![\d.])10\.\d{1,3}\.\d{1,3}\.\d{1,3}(?!\d)/],
  ['private IPv4 172.16-31.x', /(?<![\d.])172\.(1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3}(?!\d)/],
  ['tailscale', /tailscale/i],
  ['ts.net', /ts\.net/i],
  ['UUID', /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i],
  ['PDFMaker', /PDFMaker/i],
  ['LoadBehavior', /LoadBehavior/i],
  ['NAS / Synology', /\b(synology|diskstation|NAS mount)\b/i],
  ['.claude path', /\.claude[\/]/i],
  ['scratchpad path', /scratchpad/i],
];
const PATTERNS = [...GENERIC, ...LOCAL];

function walk(dir, rel = '') {
  const out = [];
  for (const e of readdirSync(join(dir, rel), { withFileTypes: true })) {
    if (e.name === '.git') continue;
    const p = rel ? rel + '/' + e.name : e.name;
    if (e.isDirectory()) out.push(...walk(dir, p));
    else if (e.isFile()) out.push(p);
  }
  return out;
}
const files = (folderArg ? walk(root) : execSync('git ls-files -z', { cwd: root, maxBuffer: 1 << 28 }).toString().split(String.fromCharCode(0)).filter(Boolean)).sort();
const hits = [];
const problems = [];
const rows = [];

for (const f of files) {
  let size = 0;
  try { size = statSync(join(root, f)).size; } catch { continue; }
  rows.push({ f, size });
  if (size > MAX) problems.push(`${f}: ${size} bytes is over 5 MB`);
  if (/\.pdf$/i.test(f) && !/^tests\/fixtures\//.test(f)) problems.push(`${f}: PDF not generated by tests/fixtures/make-fixtures.mjs`);
  if (/\.pdf$/i.test(f) && /^tests\/fixtures\//.test(f)) problems.push(`${f}: committed PDF under tests/fixtures (must be generated, not committed)`);
  if (size > MAX) continue;
  const buf = readFileSync(join(root, f));
  if (buf.subarray(0, 8000).includes(0)) continue; // binary file: not scanned as text
  const lines = buf.toString('utf8').split(/\r?\n/);
  const active = f === SELF ? LOCAL : PATTERNS;
  lines.forEach((line, i) => {
    if (line.includes('publish-check-ignore')) return;
    // Licences require the copyright holders' names and addresses: email addresses are allowed only on those lines.
    for (const [name, re] of active) {
      if (name === 'email address' && f === 'package-lock.json') continue; // third-party maintainers in dependency metadata
      if (name === 'email address' && f === 'THIRD-PARTY-NOTICES.md' && /copyright|\(c\)|©/i.test(line)) continue;
      if (EXCEPTIONS.some((e) => e.pattern === name && e.re.test(line))) continue;
      if (re.test(line)) hits.push(`${f}:${i + 1}: [${name}] ${line.trim().slice(0, 110)}`);
    }
  });
}

const DESC = {
  '(root)': 'Project files: license, notices, README, package and build configuration',
  '.github': 'GitHub Actions workflow (release)',
  build: 'Application icon sources',
  docs: 'Documentation: requirements, decisions (ADRs), testing rules, milestone blueprints, user guide, release notes',
  electron: 'Electron main process, preload and desktop-only libraries, with unit tests',
  scripts: 'Build, dev, notice-generation, corpus-download and publish-check scripts',
  src: 'The application: React user interface, core model, engine adapters (MuPDF, pdf.js), features',
  tests: 'Unit-support code, end-to-end tests, sign-off probes, engine parity, fixtures generator, trial spikes',
};
const groups = new Map();
for (const r of rows) {
  const top = r.f.includes('/') ? r.f.split('/')[0] : '(root)';
  const g = groups.get(top) ?? { n: 0, bytes: 0 };
  g.n++; g.bytes += r.size; groups.set(top, g);
}
const kb = (n) => (n / 1024).toFixed(1) + ' KB';

let md = `# Publish file list

Generated by scripts/publish-check.mjs from \`git ls-files\`. Nothing here has been published.

- Files: ${rows.length}
- Total size: ${kb(rows.reduce((a, r) => a + r.size, 0))}
- Largest file: ${rows.slice().sort((a, b) => b.size - a.size)[0]?.f} (${kb(Math.max(...rows.map((r) => r.size)))})
- Check result: ${problems.length + hits.length === 0 ? 'PASS' : `${problems.length} problem(s), ${hits.length} personal-data hit(s)`}

## Top-level folders

| Folder | Files | Size | What it is |
| --- | --- | --- | --- |
${[...groups].map(([k, g]) => `| ${k} | ${g.n} | ${kb(g.bytes)} | ${DESC[k] ?? ''} |`).join('\n')}

## Files

| Path | Size (bytes) |
| --- | --- |
${rows.map((r) => `| ${r.f} | ${r.size} |`).join('\n')}
`;
if (writeList) writeFileSync(join(repoRoot, 'docs', 'release', 'FILE-LIST.md'), md);
console.log(`${rows.length} files; ${problems.length} problem(s); ${hits.length} hit(s)`);
for (const p of problems) console.log('PROBLEM ' + p);
for (const h of hits) console.log('HIT ' + h);
process.exitCode = problems.length + hits.length ? 1 : 0;
